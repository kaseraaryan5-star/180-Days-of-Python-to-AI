# MESSAGES

#Messages are the fundamental unit of content for models in Langchain . They represent the input and output of models, carrying both the content and metadata needed to represent the state of a conversation when interacting with an LLM . Messages are objects that contains:

# 1.Role - Identifies the message type (e.g.,system,user)
# 2.Content - Represents the actual content of the message (like text, images, audio, documents, etc.)
# 3.Metadata - Optional fields such as response information, message IDs, and token usage

# Langchain provides a standard message type that works across all model providers,ensuring consistent behaviour regardless of the model being called.
