# MESSAGE PROMPTS
# Alternatively,you can pass in a list of messages to the model by providing a list of message object

# Message types
# 1.System Message - Tells the model how to behave and provide context for interactions
# 2.Human Message - Represent user input and interactions with the model
# 3.AI message  - Responses generated by the model, including text content, tool calls,and metadata
# 4.Tool Message - Represents the output of tool calls

# 1.System Message
#A SystemMessage represent an initial set of instructions that primes the model's behaviour . You can use a system message to set the tone,define the model's role,and establish guidelines for reponses

# 2.Human Message
#A HumanMessage represent user input and interactions . They can contain text, image, audio, files, and any other amount of multimodal content

# 3.AI Message
#An AIMessage represents the output of a model invocation . They can include multimodal data, tool calls, and provider-specific metadata that you can later access

# 4.Tool Message
#For models for that support tool calling, AI messages can contain tool calls . Tool messages are used to pass the results of a single tool execution back to the model

from langchain.messages import SystemMessage, HumanMessage, AIMessage

